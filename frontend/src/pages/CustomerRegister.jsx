// CustomerRegister.jsx - Task 3-1: register a new customer (calls sp_register_customer)
import { useState } from 'react';
import { api } from '../api.js';

const emptyForm = {
  firstname: '', lastname: '', address: '', city: '',
  state: '', zip: '', region: '', email: '', referred: '',
};

export default function CustomerRegister() {
  const [form, setForm] = useState(emptyForm);
  const [message, setMessage] = useState(null);
  const [newNumber, setNewNumber] = useState(null);

  const change = (e) => setForm({ ...form, [e.target.name]: e.target.value });

  const submit = async (e) => {
    e.preventDefault();
    setMessage(null);
    try {
      const res = await api.post('/api/customers', form);
      setNewNumber(res.customernumber);
      setMessage({ ok: true, text: `✅ ${res.message} — Customer number: ${res.customernumber}` });
      setForm(emptyForm);
    } catch (err) {
      setMessage({ ok: false, text: `❌ ${err.message}` });
    }
  };

  return (
    <div className="page">
      <h2>🆕 Customer Registration Form</h2>
      <p className="page-hint">Calls <code>sp_register_customer</code>; the new customer number is generated by sequence <code>JL_CUSTOMER_SEQ</code>.</p>

      <form className="card form" onSubmit={submit}>
        <div className="form-row">
          <label>First Name
            <input name="firstname" value={form.firstname} onChange={change} placeholder="Jane" />
          </label>
          <label>Last Name *
            <input name="lastname" value={form.lastname} onChange={change} required placeholder="Doe" />
          </label>
        </div>
        <label>Address
          <input name="address" value={form.address} onChange={change} placeholder="100 Main St" />
        </label>
        <div className="form-row">
          <label>City
            <input name="city" value={form.city} onChange={change} placeholder="Orlando" />
          </label>
          <label>State
            <input name="state" value={form.state} onChange={change} maxLength={2} placeholder="FL" />
          </label>
          <label>ZIP
            <input name="zip" value={form.zip} onChange={change} maxLength={10} placeholder="32801" />
          </label>
        </div>
        <div className="form-row">
          <label>Region
            <select name="region" value={form.region} onChange={change}>
              <option value="">-- region --</option>
              <option value="N">N (North)</option>
              <option value="S">S (South)</option>
              <option value="E">E (East)</option>
              <option value="W">W (West)</option>
              <option value="M">M (Midwest)</option>
            </select>
          </label>
          <label>Email
            <input type="email" name="email" value={form.email} onChange={change} placeholder="jane@mail.com" />
          </label>
          <label>Referred by (customer #)
            <input type="number" name="referred" value={form.referred} onChange={change} placeholder="1001" />
          </label>
        </div>

        <div className="form-actions">
          <button type="submit" className="btn primary">Register Customer</button>
          <button type="button" className="btn ghost" onClick={() => { setForm(emptyForm); setNewNumber(null); }}>Cancel</button>
        </div>
        {message && <div className={message.ok ? 'banner ok' : 'banner err'}>{message.text}</div>}
        {newNumber && <p className="page-hint">📌 Remember this number: <b>{newNumber}</b></p>}
      </form>
    </div>
  );
}
